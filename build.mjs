import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('.', import.meta.url);

// The Harness client module format is a single classic-script bundle:
// inline the separate BalanceCard component above the loader entry.
const component = readFileSync(new URL('src/BalanceCard.js', root), 'utf8').replace(/^export\s+/m, '');
const main = readFileSync(new URL('src/client.js', root), 'utf8').replace(/^import\s+.*$/m, '');

const banner = '/* Generated by build.mjs from src/client.js and src/BalanceCard.js. */\n\n';
writeFileSync(new URL('client.js', root), `${banner}${component.trim()}\n\n${main.trim()}\n`);
console.log('built client.js');
